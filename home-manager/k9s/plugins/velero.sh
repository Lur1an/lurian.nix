# Invoked by the Nix-packaged wrapper with K9s selection arguments.
action=$1
context=$2
namespace=$3
name=$4
resource_group=$5
velero_namespace=$namespace
label_key=""
label_resources=()
pod=""
volume=""
annotation_changed=false
old_annotation=""
had_annotation=false
backup_pending=false

kube() {
  kubectl --context "$context" --namespace "$namespace" "$@"
}

v() {
  velero --kubecontext "$context" --namespace "$velero_namespace" "$@"
}

finish() {
  local status=$?
  trap - EXIT
  set +e
  if "$backup_pending"; then
    local phase
    phase=$(v backup get "$backup_name" -o json | jq -r '.status.phase // "Unknown"')
    case "$phase" in
      Completed|PartiallyFailed|Failed|FailedValidation) ;;
      *)
        # An interrupted CLI does not cancel the server-side backup. Removing
        # its selector/annotation now could silently omit the selected data.
        printf '\nBackup %s may still be running. Keeping its temporary selection metadata.\n' "$backup_name"
        printf 'After it finishes, remove label %s from: %s\n' "$label_key" "${label_resources[*]}"
        if "$annotation_changed"; then
          printf 'Also restore pod %s annotation backup.velero.io/backup-volumes to: %s (previously present: %s)\n' \
            "$pod" "$old_annotation" "$had_annotation"
        fi
        annotation_changed=false
        label_resources=()
        ;;
    esac
  fi
  if "$annotation_changed"; then
    # Restore only if our value is still present; preserve concurrent edits.
    local patch
    patch=$(jq -cn --arg volume "$volume" --arg old "$old_annotation" --argjson had "$had_annotation" '
      [{op: "test", path: "/metadata/annotations/backup.velero.io~1backup-volumes", value: $volume},
       (if $had then {op: "replace", path: "/metadata/annotations/backup.velero.io~1backup-volumes", value: $old}
        else {op: "remove", path: "/metadata/annotations/backup.velero.io~1backup-volumes"} end)]')
    kube patch pod "$pod" --type=json -p "$patch"
  fi
  for resource in "${label_resources[@]}"; do
    kube label "$resource" "$label_key-"
  done
  if (( status != 0 )); then
    printf '\nCommand failed (exit %s).\n' "$status"
  fi
  read -r -p "Press Enter to return to K9s... " _ || true
  exit "$status"
}
trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Resource names such as "backups" are also used by other operators.
case "$action" in
  backup-*|restore-*|schedule-*)
    if [[ "$resource_group" != velero.io ]]; then
      echo "Select a velero.io resource for this action." >&2
      exit 1
    fi
    ;;
esac

prompt_namespace() {
  read -r -p "Velero installation namespace [velero]: " velero_namespace
  velero_namespace=${velero_namespace:-velero}
}

prompt_backup() {
  local default
  default="${name:0:180}-$(date -u +%Y%m%d%H%M%S)"
  read -r -p "Backup name [$default]: " backup_name
  backup_name=${backup_name:-$default}
}

label_resource() {
  # A unique key avoids modifying existing labels used by other backups.
  label_resources+=("$1")
  kube label "$1" "$label_key=true"
}

case "$action" in
  backup-describe|restore-describe)
    v "${action%-describe}" describe "$name" --details 2>&1 | less -R
    ;;
  backup-logs|restore-logs)
    v "${action%-logs}" logs "$name" 2>&1 | less -R
    ;;
  backup-delete)
    v backup delete "$name" --confirm
    ;;
  backup-restore)
    read -r -p "Restore name [generated by Velero]: " restore_name
    read -r -p "Namespace mappings [original namespaces; or source:target,...]: " mappings
    args=(restore create)
    [[ -z "$restore_name" ]] || args+=("$restore_name")
    args+=(--from-backup "$name")
    [[ -z "$mappings" ]] || args+=(--namespace-mappings "$mappings")
    v "${args[@]}"
    ;;
  schedule-backup)
    prompt_backup
    v backup create "$backup_name" --from-schedule "$name"
    ;;
  schedule-pause|schedule-unpause)
    v schedule "${action#schedule-}" "$name"
    ;;
  namespace-backup)
    prompt_namespace
    prompt_backup
    read -r -p "Volume backup method [filesystem/snapshot] (filesystem): " method
    case "${method:-filesystem}" in
      filesystem) args=(--default-volumes-to-fs-backup --snapshot-volumes=false) ;;
      snapshot) args=(--snapshot-volumes --snapshot-move-data) ;;
      *) echo "Unknown backup method: $method" >&2; exit 1 ;;
    esac
    v backup create "$backup_name" --include-namespaces "$name" "${args[@]}"
    ;;
  pvc-filesystem|pvc-snapshot)
    prompt_namespace
    prompt_backup
    pvc=$(kube get pvc "$name" -o json)
    if [[ $(jq -r '.status.phase' <<< "$pvc") != Bound ]]; then
      echo "The selected PVC must be Bound." >&2
      exit 1
    fi
    args=(--include-namespaces "$namespace")
    if [[ "$action" == pvc-filesystem ]]; then
      if [[ $(jq -r '.spec.volumeMode // "Filesystem"' <<< "$pvc") != Filesystem ]]; then
        echo "Filesystem backup requires a filesystem-mode PVC." >&2
        exit 1
      fi
      pods=$(kube get pods -o json)
      mapfile -t candidates < <(jq -r --arg pvc "$name" '
        .items[] | select(.status.phase == "Running") |
        select(any(.spec.volumes[]?; .persistentVolumeClaim.claimName == $pvc)) |
        .metadata.name' <<< "$pods")
      if (( ${#candidates[@]} == 0 )); then
        echo "No running pod mounts this PVC. Mount it in a pod before using filesystem backup." >&2
        exit 1
      elif (( ${#candidates[@]} == 1 )); then
        pod=${candidates[0]}
      else
        echo "Choose the pod to use for the volume backup:"
        select pod in "${candidates[@]}"; do
          [[ -z "$pod" ]] || break
        done
        [[ -n "$pod" ]] || exit 1
      fi
      pod_json=$(kube get pod "$pod" -o json)
      volume=$(jq -r --arg pvc "$name" '[.spec.volumes[] |
        select(.persistentVolumeClaim.claimName == $pvc) | .name][0]' <<< "$pod_json")
      if [[ "$volume" == null ]]; then
        echo "The pod no longer references the PVC." >&2
        exit 1
      fi
      had_annotation=$(jq '(.metadata.annotations // {}) | has("backup.velero.io/backup-volumes")' <<< "$pod_json")
      old_annotation=$(jq -r '.metadata.annotations["backup.velero.io/backup-volumes"] // ""' <<< "$pod_json")
      if jq -e --arg volume "$volume" '
        (.metadata.annotations["backup.velero.io/backup-volumes-excludes"] // "" | split(",")) |
        index($volume) != null' <<< "$pod_json" >/dev/null; then
        echo "This pod explicitly excludes the selected volume from filesystem backup." >&2
        exit 1
      fi
      args+=(--include-resources "pods,persistentvolumeclaims,persistentvolumes"
        --default-volumes-to-fs-backup=false --snapshot-volumes=false)
    else
      args+=(--include-resources "persistentvolumeclaims,persistentvolumes"
        --snapshot-volumes --snapshot-move-data)
    fi
    label_key="k9s.velero.io/selection-$(date +%s)-$$"
    label_resource "pvc/$name"
    if [[ "$action" == pvc-filesystem ]]; then
      label_resource "pod/$pod"
      annotation_changed=true
      kube annotate pod "$pod" "backup.velero.io/backup-volumes=$volume" --overwrite
      printf 'Backing up %s from pod %s (volume %s).\n' "$name" "$pod" "$volume"
    fi
    # Keep the selector and annotation until Velero finishes processing them.
    backup_pending=true
    v backup create "$backup_name" "${args[@]}" --selector "$label_key=true" --wait
    backup_pending=false
    v backup describe "$backup_name" --details
    ;;
  *)
    echo "Unknown action: $action" >&2
    exit 1
    ;;
esac
